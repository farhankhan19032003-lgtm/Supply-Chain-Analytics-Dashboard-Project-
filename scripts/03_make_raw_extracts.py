#!/usr/bin/env python3
"""
03_make_raw_extracts.py
-----------------------
Creates the deliberately MESSY inputs for the Excel Power Query exercise, from the clean data:

  data/raw_regional_extracts/
      North_Weekly_Stock_FY26.csv     dd-mm-yyyy dates, trailing spaces, lower-case SKUs, "1,234" text numbers,
                                      duplicate rows, empty rows, free-text Remarks column
      West_Weekly_Stock_FY26.csv      3-line report preamble, different headers, yyyy/mm/dd dates,
                                      warehouse given by NAME (not code)
      South_Weekly_Stock_FY26.csv     semicolon-delimited, dd-Mon-yyyy dates, "NA" text in numeric columns
      East_Weekly_Stock_FY26.csv      columns in a different order, dd/mm/yyyy dates, negative closing stock typos
      Central_Weekly_Stock_FY26.csv   timestamps in the date column, Closing Stock missing on ~12% rows
      Master_Data_Raw.xlsx            SKU / Supplier / Warehouse masters with title rows, padded + upper-case names

Scope: the last 52 weeks (FY26 H2 + FY27 H1 view), 74,880 clean rows expected after Power Query.
Deterministic (fixed seed).

Run: python3 scripts/03_make_raw_extracts.py
"""
import os

import numpy as np
import pandas as pd
from openpyxl import Workbook

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA, OUT = f"{ROOT}/data/clean", f"{ROOT}/data/raw_regional_extracts"
os.makedirs(OUT, exist_ok=True)
rng = np.random.default_rng(7)

inv = pd.read_csv(f"{DATA}/fact_inventory_weekly.csv")
wh = pd.read_csv(f"{DATA}/dim_warehouse.csv")
sku = pd.read_csv(f"{DATA}/dim_sku.csv")
sup = pd.read_csv(f"{DATA}/dim_supplier.csv")

weeks = sorted(inv["week_start"].unique())[-52:]
inv = inv[inv["week_start"].isin(weeks)].merge(wh[["warehouse_id", "warehouse_name", "region"]], on="warehouse_id")
NUM = ["opening_stock", "receipts", "demand_units", "units_sold", "lost_units", "closing_stock"]
manifest = {}

def thousands_text(df, cols, share):
    """turn some numbers >= 1000 into text with a thousands separator, e.g. '1,234'"""
    df = df.copy()
    for c in cols:
        df[c] = df[c].astype(object)
        m = (rng.random(len(df)) < share) & (pd.to_numeric(df[c], errors="coerce") >= 1000)
        df.loc[m, c] = df.loc[m, c].map(lambda v: f"{int(v):,}")
    return df

def add_dupes_and_blanks(df, dupe_share, blank_share):
    dup = df.sample(frac=dupe_share, random_state=int(rng.integers(1e6)))
    out = pd.concat([df, dup]).sample(frac=1.0, random_state=int(rng.integers(1e6))).reset_index(drop=True)
    n_blank = int(len(out) * blank_share)
    for pos in sorted(rng.choice(len(out), size=n_blank, replace=False), reverse=True):
        out = pd.concat([out.iloc[:pos], pd.DataFrame([{c: "" for c in out.columns}]), out.iloc[pos:]]).reset_index(drop=True)
    return out, len(dup), n_blank

# ----------------------------------------------------------------------------------- NORTH
n = inv[inv["region"] == "North"].copy()
manifest["North"] = len(n)
df = pd.DataFrame({
    "Wk Start": pd.to_datetime(n["week_start"]).dt.strftime("%d-%m-%Y"),
    "WH Code": np.where(rng.random(len(n)) < 0.15, n["warehouse_id"] + " ", n["warehouse_id"]),
    "SKU Code": np.where(rng.random(len(n)) < 0.10, n["sku_id"].str.lower(), n["sku_id"]),
    "Opening Stock": n["opening_stock"], "Receipts": n["receipts"], "Demand": n["demand_units"],
    "Sold": n["units_sold"], "Lost": n["lost_units"], "Closing Stock": n["closing_stock"],
    "Remarks": rng.choice(["", "", "", "", "ok", "recount", "pending audit"], size=len(n))})
df = thousands_text(df, ["Opening Stock", "Receipts", "Demand", "Sold", "Closing Stock"], 0.20)
df, nd, nb = add_dupes_and_blanks(df, 0.004, 0.002)
df.to_csv(f"{OUT}/North_Weekly_Stock_FY26.csv", index=False)
print(f"North   rows={len(df):>6,d}  (clean {manifest['North']:,}, dupes {nd}, blank {nb})")

# ----------------------------------------------------------------------------------- WEST
w = inv[inv["region"] == "West"].copy()
manifest["West"] = len(w)
df = pd.DataFrame({
    "week_start": pd.to_datetime(w["week_start"]).dt.strftime("%Y/%m/%d"),
    "warehouse": w["warehouse_name"], "sku": w["sku_id"],
    "open_qty": w["opening_stock"], "recv_qty": w["receipts"], "demand_qty": w["demand_units"],
    "sales_qty": w["units_sold"], "lost_qty": w["lost_units"], "close_qty": w["closing_stock"]})
body = df.to_csv(index=False)
with open(f"{OUT}/West_Weekly_Stock_FY26.csv", "w", newline="") as fh:
    fh.write("Western Region Weekly Stock Report\nGenerated by WMS export v2.3\n\n" + body)
print(f"West    rows={len(df):>6,d}  (3-line preamble)")

# ----------------------------------------------------------------------------------- SOUTH
s = inv[inv["region"] == "South"].copy()
manifest["South"] = len(s)
df = pd.DataFrame({
    "Week": pd.to_datetime(s["week_start"]).dt.strftime("%d-%b-%Y"),
    "Warehouse_ID": s["warehouse_id"], "Item": s["sku_id"],
    "Opening": s["opening_stock"], "Inbound": s["receipts"], "Demand": s["demand_units"],
    "Units Sold": s["units_sold"], "Lost Sales": s["lost_units"].astype(object), "Closing": s["closing_stock"]})
na = (df["Lost Sales"] == 0) & (rng.random(len(df)) < 0.10)
df.loc[na, "Lost Sales"] = "NA"
df.to_csv(f"{OUT}/South_Weekly_Stock_FY26.csv", index=False, sep=";")
print(f"South   rows={len(df):>6,d}  ('NA' in Lost Sales: {int(na.sum())})")

# ----------------------------------------------------------------------------------- EAST
e = inv[inv["region"] == "East"].copy()
manifest["East"] = len(e)
df = pd.DataFrame({
    "SKU": e["sku_id"], "Warehouse": e["warehouse_id"],
    "Week Commencing": pd.to_datetime(e["week_start"]).dt.strftime("%d/%m/%Y"),
    "Closing Stock": e["closing_stock"].astype(object), "Units Sold": e["units_sold"], "Demand": e["demand_units"],
    "Lost Units": e["lost_units"], "Receipts": e["receipts"], "Opening Stock": e["opening_stock"]})
neg = (df["Closing Stock"] > 0) & (rng.random(len(df)) < 0.001)
df.loc[neg, "Closing Stock"] = -df.loc[neg, "Closing Stock"]
df.to_csv(f"{OUT}/East_Weekly_Stock_FY26.csv", index=False)
print(f"East    rows={len(df):>6,d}  (negative closing typos: {int(neg.sum())})")

# ----------------------------------------------------------------------------------- CENTRAL
c = inv[inv["region"] == "Central"].copy()
manifest["Central"] = len(c)
df = pd.DataFrame({
    "week_start": pd.to_datetime(c["week_start"]).dt.strftime("%Y-%m-%d 00:00:00"),
    "warehouse_id": c["warehouse_id"], "sku_id": c["sku_id"],
    "opening_stock": c["opening_stock"], "receipts": c["receipts"], "demand_units": c["demand_units"],
    "units_sold": c["units_sold"], "lost_units": c["lost_units"].astype(object),
    "closing_stock": c["closing_stock"].astype(object)})
miss = rng.random(len(df)) < 0.12
df.loc[miss, "closing_stock"] = ""
df.loc[(df["lost_units"] == 0) & (rng.random(len(df)) < 0.05), "lost_units"] = ""
df.to_csv(f"{OUT}/Central_Weekly_Stock_FY26.csv", index=False)
print(f"Central rows={len(df):>6,d}  (closing_stock missing: {int(miss.sum())})")

pd.Series(manifest).to_csv(f"{OUT}/_expected_clean_rows_by_region.csv", header=["clean_rows"], index_label="region")
print("Expected clean rows after Power Query:", sum(manifest.values()))

# ----------------------------------------------------------------------------------- MASTER DATA (xlsx)
wb = Workbook()
ws = wb.active
ws.title = "SKU_Master"
ws.append(["Master Data Extract - SKU List"])
ws.append(["Source: ERP item master | Do not edit"])
ws.append(["SKU Code", "Item Description", "Category", "Unit Cost (INR)", "Unit Price (INR)", "Lead Time (days)",
           "Primary Supplier Code", "ABC"])
for _, r in sku.iterrows():
    ws.append([r.sku_id.lower() if rng.random() < 0.1 else r.sku_id, "  " + r.sku_name.upper() + "  ", r.category,
               r.unit_cost_inr, r.unit_price_inr, int(r.lead_time_days), r.primary_supplier_id, r.abc_class])

ws2 = wb.create_sheet("Supplier_Master")
ws2.append(["Supplier master (procurement)"])
ws2.append(["Supplier Code", "Supplier Name", "Category", "Origin City", "Origin Region", "Payment Terms (days)"])
for _, r in sup.iterrows():
    nm = r.supplier_name
    nm = nm.upper() if rng.random() < 0.3 else (" " + nm + " " if rng.random() < 0.3 else nm)
    ws2.append([r.supplier_id, nm, r.category, r.origin_city, r.origin_region, int(r.payment_terms_days)])

ws3 = wb.create_sheet("Warehouse_Master")
ws3.append(["Warehouse master (network planning)"])
ws3.append(["Code", "Name", "City", "State", "Region", "Lat", "Lon", "Capacity (units)"])
for _, r in wh.iterrows():
    ws3.append([r.warehouse_id, r.warehouse_name, r.city, r.state, r.region, r.latitude, r.longitude, int(r.capacity_units)])
wb.save(f"{OUT}/Master_Data_Raw.xlsx")
print("Master_Data_Raw.xlsx written (SKU_Master / Supplier_Master / Warehouse_Master)")
